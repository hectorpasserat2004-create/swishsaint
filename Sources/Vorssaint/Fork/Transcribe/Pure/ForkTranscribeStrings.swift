import Foundation

/// File Transcription's texts. Same contract as the other fork strings:
/// memberwise init in declaration order, one static per language. A text
/// with `%@` or `%d` is a format.
struct ForkTranscribeStrings {
    let pageIntro: String
    let dropTitle: String
    let chooseFiles: String
    let dropRefused: String
    let engineTitle: String
    let engineLocal: String
    let engineLocalDetail: String
    let modelReady: String
    let modelMissing: String
    let modelInstall: String
    /// %d: percent.
    let modelDownloading: String
    let languageTitle: String
    let languageAuto: String
    let languageFrench: String
    let languageEnglish: String
    let outputTitle: String
    let outputBeside: String
    let outputFolder: String
    let chooseFolder: String
    let formatsTitle: String
    let replacementsTitle: String
    let notifyTitle: String
    let inProgress: String
    let finished: String
    let cancelAll: String
    let clearList: String
    let empty: String
    let stageQueued: String
    let stageWaitingForModel: String
    let stageWaitingForEngine: String
    let stageLoading: String
    let stageTranscribing: String
    /// %@: "0:42".
    let stageRemaining: String
    let stageWriting: String
    let stageCancelled: String
    /// %d: words.
    let doneWords: String
    /// %@: "0:42".
    let doneIn: String
    let fallbackNote: String
    let failureFileMissing: String
    let failureNotDownloaded: String
    let failureUnreadable: String
    let failureNoAudio: String
    let failureModelMissing: String
    let failureEngine: String
    let failureNothingHeard: String
    let failureWriteFailed: String
    let failureInterrupted: String
    let open: String
    let retry: String
    let showInFinder: String
    let remove: String
    let cancel: String
    let copyDiagnostic: String
    let copyAll: String
    let copyForAssistant: String
    let copied: String
    let search: String
    let close: String
    let textMissing: String
    /// %@: the file's name.
    let fileTitle: String
    /// %1$@: the length, %2$@: the date.
    let fileSummaryLocal: String
    /// %d: the voice's number.
    let voice: String
    /// After a voice's name: ": ", or " : " in French.
    let separator: String
    let noticeDone: String
    let noticeFailed: String
    let barTranscribe: String
    let barOpen: String
    let barKeywords: String

    static func strings(_ language: AppLanguage) -> ForkTranscribeStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }

    func failure(_ failure: ForkTranscribeFailure) -> String {
        switch failure {
        case .fileMissing: return failureFileMissing
        case .notDownloaded: return failureNotDownloaded
        case .unreadable: return failureUnreadable
        case .noAudio: return failureNoAudio
        case .modelMissing: return failureModelMissing
        case .engine: return failureEngine
        case .nothingHeard: return failureNothingHeard
        case .writeFailed: return failureWriteFailed
        case .interrupted: return failureInterrupted
        }
    }

    func language(_ language: ForkTranscribeLanguage) -> String {
        switch language {
        case .auto: return languageAuto
        case .fr: return languageFrench
        case .en: return languageEnglish
        }
    }
}

