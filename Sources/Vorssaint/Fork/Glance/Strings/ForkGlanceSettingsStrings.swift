import Foundation

/// The words of the Glance Focus settings page (plan §12) and of its
/// diagnostics (§12.11). The words every surface shares (modes, splits,
/// grades, option labels, durations, notices, buttons) are the core's
/// (`ForkGlanceStrings`): only the page's own sentences live here.
///
/// Same contract as the core: memberwise init in declaration order, one
/// static per language, placeholders filled by `ForkGlanceStrings.fill`
/// (`%@`, or `%1$@` and `%2$@`), never by `String(format:)`. French:
/// `\u{00A0}` before « : ; ! ? » and inside « », typographic apostrophes.
struct ForkGlanceSettingsStrings {
    // MARK: Banners
    /// Under « Calibrez pour cette disposition » and beside « Calibrer… ».
    let calibrationCaption: String
    /// Under a camera that is missing, unplugged or failing.
    let cameraProblemCaption: String
    /// Under « Le regard se trompe souvent ».
    let driftCaption: String
    /// The layout moved a little since the calibration (plan §8.6, case 2).
    let layoutMovedTitle: String
    let layoutMovedCaption: String

    // MARK: Permissions (plan §12.2)
    let permissionsTitle: String
    let camera: String
    let cameraPermissionCaption: String
    let cameraDeniedCaption: String

    // MARK: Calibration (plan §12.3)
    let calibrationTitle: String
    let notCalibrated: String
    /// `%@`: a date, « Calibré le 23 oct. 2026 ».
    let calibratedOn: String
    let deleteProfile: String
    /// `%@`: a profile's name.
    let deleteProfileTitle: String
    let deleteProfileMessage: String
    let delete: String
    let cancel: String
    let otherProfiles: String

    // MARK: Layout and mode (plan §12.4)
    let layoutTitle: String
    let mapCaption: String
    let noDisplays: String
    /// The title of a display's split menu.
    let splitTitle: String
    let modeTitle: String
    let modeUnknownFit: String
    let panesCaption: String
    let panesClickFallback: String
    let panesClickFallbackCaption: String
    let panesAppsTitle: String
    let panesAppsCaption: String

    // MARK: Behavior (plan §12.5)
    let behaviorTitle: String
    let sensitivityTitle: String
    let dwellTitle: String
    let typingPauseTitle: String
    let pointerPauseTitle: String
    let raiseTitle: String
    let raiseCaption: String
    let pointerTitle: String
    let pointerAutoCaption: String
    /// The official « Focus follows mouse » is on (plan §6.3).
    let pointerFocusFollowsMouse: String
    let feedbackTitle: String
    let learnTitle: String
    let learnCaption: String

    // MARK: Apps (plan §12.6)
    let appsTitle: String
    let neverLeaveTitle: String
    let neverLeaveCaption: String
    let neverFocusTitle: String
    let neverFocusCaption: String
    let addApp: String
    let removeApp: String

    // MARK: Camera and energy (plan §12.7)
    let cameraEnergyTitle: String
    let cameraAutomatic: String
    let checkFraming: String
    let energyTitle: String
    let energyCaption: String
    let batteryTitle: String
    let lowPowerTitle: String
    let idleOffTitle: String
    let idleOffCaption: String
    let callsTitle: String
    let callsCaption: String
    let costTitle: String
    /// `%1$@`: a share of a core, `%2$@`: a power, « ≈ 2 % d’un cœur · ≈ 0,1 W (processus) ».
    let costLine: String
    /// `%@`: a share of a core, before the power is known.
    let costCPUOnly: String
    let costMeasuring: String
    let costNotRunning: String
    let costCameraNote: String

    // MARK: Shortcuts (plan §12.8)
    let shortcutsTitle: String
    let shortcutPrompt: String
    let shortcutNone: String
    let shortcutRemove: String
    let shortcutReserved: String
    let shortcutNeedsModifier: String
    let shortcutConflict: String
    let recenterCaption: String

    // MARK: Dynamic Island (plan §12.9)
    let islandTitle: String
    let islandRow: String
    let islandRowCaption: String
    let islandOpen: String

    // MARK: Privacy (plan §12.10)
    let privacyTitle: String
    let privacyAnalyzed: String
    let privacyNothingSaved: String
    let privacyStaysHere: String
    let privacyNoRecognition: String
    let privacyLight: String

    // MARK: Diagnostics (plan §12.11)
    let diagnosticsTitle: String
    let diagnosticsCaption: String
    let diagnosticsIdle: String
    let previewUnavailable: String
    let curvesTitle: String
    let curveYaw: String
    let curvePitch: String
    let curveEyes: String
    let estimateTitle: String
    /// The diagnostic gaze dot over every display (`fork.glance.gazeDot`).
    let showGazeDot: String
    let rowFrameRate: String
    /// `%@`: images per second.
    let frameRateValue: String
    let rowVision: String
    /// `%1$@`: the mean, `%2$@`: the 95th percentile, in milliseconds.
    let visionValue: String
    let rowConfidence: String
    let rowGuards: String
    let rowPhase: String
    let rowLastSwitch: String
    let rowFocusFailures: String
    let rowClickAgreement: String
    let rowExtraEntry: String
    /// `%@`: a margin in σ, « +0,5 σ ».
    let extraEntryValue: String
    let rowSetAside: String
    let rowRevisions: String
    /// An empty list in the table.
    let none: String
    let recordTrace: String
    let recordingTrace: String
    let traceSaved: String
    let traceNotSaved: String
    let traceCaption: String
    let copyReport: String
    let reportCopied: String

    static func strings(_ language: AppLanguage) -> ForkGlanceSettingsStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }
}

