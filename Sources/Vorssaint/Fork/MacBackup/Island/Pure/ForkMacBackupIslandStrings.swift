import Foundation

/// The words of Mac Backup's island screens: the section, the closed
/// island's activity, the notices, the cards, the island's settings and the
/// Command Bar. The states, buttons, causes and chain words they share with
/// the other screens are in `ForkMacBackupStrings` (frozen).
///
/// Same contract as the official FeatureStrings structs: memberwise init in
/// declaration order, one static per language. Everything shown in the
/// island fits in 28 characters once filled (tested); the sentences and the
/// Command Bar's rows are longer. French: `\u{00A0}` before « : ; ! ? »,
/// typographic apostrophes.
struct ForkMacBackupIslandStrings {
    // MARK: Section
    /// The section's line in the island's Content tab.
    let sectionSummary: String
    /// The section before anything is set up.
    let emptyMessage: String
    /// `%@`: a count of files, « 18 204 fichiers lus ».
    let filesRead: String
    let errorsNone: String
    /// Russian and Ukrainian carry `%d` here too (21, 31…).
    let errorsOne: String
    let errorsFew: String
    let errorsMany: String
    /// `%@`: a proof level, read aloud.
    let proofSpoken: String
    /// `%@`: every node and its state, read aloud.
    let chainSpoken: String
    let chainHint: String
    /// The partial backup's button.
    let see: String
    let seeHint: String
    let sources: String
    let sourceDone: String
    let sourceRunning: String
    let sourceWaiting: String
    let sourceFailed: String
    let sourceNever: String
    /// The closed island's activity and the tile, read aloud.
    let activityHint: String

    // MARK: Island settings (Content and Activity tabs)
    let closedIsland: String
    let closedIslandCaption: String
    let compactRunning: String
    let compactNever: String
    let rightWing: String
    let readingPercent: String
    let readingRemaining: String
    let endNotices: String
    let noticeComplete: String
    let noticePartial: String
    let noticeFailed: String
    let noticeRestore: String
    let noticesCaption: String
    let showChain: String
    let showPending: String
    let sectionSize: String
    let sizeCompact: String
    let sizeSpacious: String
    let allSettings: String
    let islandSettings: String

    // MARK: Notices
    let restoredOne: String
    let restoredFew: String
    let restoredMany: String

    // MARK: Cards
    let firstTitle: String
    /// `%@`: a size.
    let firstCaption: String
    let firstCaptionUnknown: String
    let chooseContent: String
    let startOnPower: String
    let showInFinder: String
    let open: String
    let branTitle: String
    let branCaption: String
    let stopBran: String
    let later: String

    // MARK: Command Bar
    let barBackUpNow: String
    let barPause: String
    let barResume: String
    let barStatus: String
    let barRestore: String
    let barNotBackedUp: String
    let barVerify: String
    let barKit: String
    let barKeywords: String

    static func strings(_ language: AppLanguage) -> ForkMacBackupIslandStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }

    /// « 3 errors » in the language's own agreement; « no errors » for none.
    func errors(_ count: Int, language: AppLanguage) -> String {
        count <= 0 ? errorsNone
            : ForkMacBackupStrings.counted(count, language: language, one: errorsOne, few: errorsFew, many: errorsMany)
    }

    /// « 214 files restored » in the language's own agreement.
    func restored(_ count: Int, language: AppLanguage) -> String {
        ForkMacBackupStrings.counted(count, language: language, one: restoredOne, few: restoredFew, many: restoredMany)
    }
}

