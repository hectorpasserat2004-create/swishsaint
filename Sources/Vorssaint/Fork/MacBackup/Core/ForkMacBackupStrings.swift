/// The Mac Backup words several parts share: the feature's name, its states,
/// the proof levels, the buttons, the failure causes and their remedies, the
/// chain's nodes. Each work package keeps the words of its own screens in a
/// strings file of its own; these are frozen, so the packages agree.
///
/// Same contract as the official FeatureStrings structs: memberwise init in
/// declaration order, one static per language. Every field marked *island*
/// fits in 28 characters once its placeholder is filled (tested).
/// French: `\u{00A0}` before « : ; ! ? » and inside « », typographic
/// apostrophes.
struct ForkMacBackupStrings {
    // MARK: Names
    /// The feature, in the Settings and the Extras page.
    let featureTitle: String
    /// The island's section and the Command Bar (island).
    let islandTitle: String
    /// A home folder as a source: « Dossier personnel », never the account's name.
    let homeFolder: String

    // MARK: States (island)
    let off: String
    let notConfigured: String
    let protected: String
    /// `%@`: an age, « 2 h ».
    let protectedAgo: String
    /// `%@`: a time of day.
    let nextAt: String
    let checkingChain: String
    let preparing: String
    let scanning: String
    /// `%@`: a percentage or a time left.
    let running: String
    /// `%@`: a percentage or a time left.
    let slowed: String
    let concluding: String
    /// While the time left is not stable yet.
    let calculating: String
    /// `%@`: a compact count, « 1,2 M » (island).
    let preparingExamined: String
    /// `%@`: a duration.
    let remaining: String
    let finished: String
    /// The form for one; Russian and Ukrainian use it for 21, 31… too, so
    /// theirs carries `%d` where the others write « 1 ».
    let partialOne: String
    /// `%d`: the count, for the languages with a form between one and many
    /// (`CountAgreement`); the same as `partialMany` elsewhere.
    let partialFew: String
    let partialMany: String
    let failed: String
    let paused: String
    /// `%@`: a time of day or a day.
    let pausedUntil: String
    let restoring: String
    let verifying: String
    let maintaining: String

    // MARK: Waiting (island)
    let waitPower: String
    let waitBattery: String
    let waitLowPower: String
    let waitNetwork: String
    let waitLimitedNetwork: String
    let waitPeer: String
    let waitMeeting: String
    let waitApproval: String
    let waitDiskAccess: String
    let waitEngine: String
    let wrongRepository: String
    let waitLocalSpace: String
    let waitRules: String
    let waitOtherEngine: String
    /// `%@`: a duration, after a waiting reason.
    let forcedIn: String

    // MARK: Proof levels (island)
    let proofPresent: String
    let proofComplete: String
    let proofVerified: String
    let proofRestored: String

    // MARK: Buttons (island)
    let backUpNow: String
    let backUpAnyway: String
    let pause: String
    let resume: String
    let slowDown: String
    let restore: String
    let verify: String
    let configure: String
    let openBackups: String
    let pauseOneHour: String
    let pauseUntilTomorrow: String
    let pauseUntilResumed: String

    // MARK: A file's failure (island) and its remedy
    let causeCloudOnly: String
    let causePermission: String
    let causeBusy: String
    let causeVanished: String
    let causeOther: String
    let remedyCloudOnly: String
    let remedyPermission: String
    let remedyBusy: String
    let remedyOther: String

    // MARK: A run's failure (island) and its remedy (a sentence)
    let runChainBroken: String
    let runAuthentication: String
    let runEngineStopped: String
    let runNoSnapshot: String
    let runStalled: String
    let runCanceled: String
    let runOther: String
    let fixChain: String
    let fixWrongRepository: String
    let fixAuthentication: String
    let fixEngine: String
    let fixDiskAccess: String
    let fixSpace: String
    let fixRetry: String

    // MARK: The chain (island)
    let nodeMac: String
    let nodeNetwork: String
    let nodeTailscale: String
    let nodeName: String
    let nodeS3: String
    let nodeRepository: String
    let nodeProxmox: String
    let nodeNAS: String
    let nodeCloud: String
    let nodeOK: String
    let nodeSlow: String
    let nodeBroken: String
    let nodeUnknown: String

    // MARK: Changes not protected yet (island)
    let pendingOne: String
    let pendingFew: String
    let pendingMany: String

    // MARK: Lines (section, settings, window)
    let lastBackup: String
    let lastComplete: String
    let never: String
    let rhythmAuto: String
    /// `%@`: a duration, « 2 h ».
    let rhythmAbout: String
    let rhythmEvery: String
    /// `%@`: a list of times.
    let rhythmTimes: String
    let protectedSize: String
    let sentSize: String
    let repositorySize: String
    let freeSpace: String
    let unknown: String
    /// A size or a cost not measured yet: known once a backup ran (island).
    let afterFirstBackup: String
    /// `%@` × 3: a duration, a battery percentage, a size.
    let costLine: String

    static func strings(_ language: AppLanguage) -> ForkMacBackupStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }

    /// « Partial · 3 files » in the language's own agreement.
    func partial(_ count: Int, language: AppLanguage) -> String {
        Self.counted(count, language: language, one: partialOne, few: partialFew, many: partialMany)
    }

    /// « 214 files waiting » in the language's own agreement.
    func pending(_ count: Int, language: AppLanguage) -> String {
        Self.counted(count, language: language, one: pendingOne, few: pendingFew, many: pendingMany)
    }

    /// Picks the form for `count` (`CountAgreement`) and fills its `%d`.
    static func counted(_ count: Int, language: AppLanguage, one: String, few: String, many: String) -> String {
        let form: String
        switch language.countAgreement {
        case .oneAndMany:
            form = count == 1 ? one : many
        case .byLastDigits:
            let lastTwo = abs(count) % 100
            let last = abs(count) % 10
            if last == 1 && lastTwo != 11 {
                form = one
            } else if (2...4).contains(last) && !(12...14).contains(lastTwo) {
                form = few
            } else {
                form = many
            }
        case .byWholeNumber:
            form = count == 1 ? one : ((2...4).contains(count) ? few : many)
        }
        return form.replacingOccurrences(of: "%d", with: String(count))
    }
}

